export interface PublicFieldDetails {
  fields: string[];
}

export function fieldLabel(fieldOrPath: unknown): string {
  const segments = pathSegments(fieldOrPath);
  const normalizedSegments = segments
    .filter((segment) => segment && !/^\d+$/.test(segment))
    .map(camelToSnake);
  for (let index = 0; index < normalizedSegments.length - 1; index += 1) {
    const contextualLabel = fieldLabels[normalizedSegments.slice(index).join(".")];
    if (contextualLabel) return contextualLabel;
  }
  for (let index = segments.length - 1; index >= 0; index -= 1) {
    const segment = segments[index];
    if (!segment || /^\d+$/.test(segment)) continue;
    if (/[\u3400-\u9fff]/u.test(segment)) return segment;
    const normalized = camelToSnake(segment);
    const label = fieldLabels[normalized];
    if (label) return label;
  }
  return "填写内容";
}

export function validationFieldDetails(issues: readonly unknown[]): PublicFieldDetails {
  const fields = uniqueLabels(issues.map((issue) => fieldLabel(issuePath(issue))));
  return { fields: fields.length ? fields : ["填写内容"] };
}

export function normalisePublicFieldDetails(details: unknown): PublicFieldDetails | null {
  if (Array.isArray(details)) return validationFieldDetails(details);
  if (!details || typeof details !== "object") return null;
  const fields = (details as { fields?: unknown }).fields;
  if (!Array.isArray(fields)) return null;
  const labels = uniqueLabels(fields.map(fieldLabel));
  return { fields: labels.length ? labels : ["填写内容"] };
}

function issuePath(issue: unknown): unknown {
  if (!issue || typeof issue !== "object") return undefined;
  return (issue as { path?: unknown }).path;
}

function pathSegments(value: unknown): string[] {
  if (Array.isArray(value)) {
    return value.flatMap((item) => (
      typeof item === "string" || typeof item === "number" ? [String(item)] : []
    ));
  }
  if (typeof value === "number") return [String(value)];
  if (typeof value !== "string") return [];
  return value.split(/[.[\]]+/u).filter(Boolean);
}

function uniqueLabels(labels: readonly string[]): string[] {
  return [...new Set(labels)];
}

function camelToSnake(value: string): string {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}
