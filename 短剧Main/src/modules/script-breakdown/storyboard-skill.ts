/** 阶段②输出 JSON 的 schema 说明（skill 态）。shotsPerSegment：1..MAX 生效则要求每段恰好 N 个，null=自由。 */
export function storyboardOutputSchemaPrompt(shotsPerSegment: number | null): string {
  const shotsShape = shotsPerSegment !== null
    ? `"shots": [ 恰好 ${shotsPerSegment} 个 { "subject_action": "主体动作", "physics_detail": "物理细节", "camera_language": "镜头语言", "lighting": "光影" } ]`
    : `"shots": [ 若干(≥1)个 { "subject_action": "主体动作", "physics_detail": "物理细节", "camera_language": "镜头语言", "lighting": "光影" } ]`;
  const shotsRule = shotsPerSegment !== null
    ? `- 本次任务指定每个 Segment 拆 ${shotsPerSegment} 个 Shot:shots 数组必须恰好 ${shotsPerSegment} 个,不多不少;`
    : `- 每个 Segment 的 shots 数组至少 1 个,数量由剧情内容自然决定(不固定);`;
  return [
    "## 输出要求",
    "只输出一个 JSON 对象,不要输出 JSON 以外的任何内容。形状如下:",
    `{ "segments": [ {
  "segment_title": "本段标题(中文)",
  "scene_ref": 该段所属场次的序号(整数,从「场次清单」里选),
  "covered_line_range": [起始行号, 结束行号],
  "duration_sec": 该分镜秒数(1-60 的整数,按剧本节奏分配),
  "assets": [ { "kind": "character|scene|prop|costume|audio|light_ref|photo_ref|video_ref", "name": "资产名(照抄资产库清单)" } ],
  "audio": { "sfx_layers": ["音效描述"], "dialogue": [ { "speaker": "角色名|null", "text": "对白原文", "lip_sync": true } ] },
  "style": { "art_style": "画风", "color_tone": "色调", "camera_strategy": "运镜策略" },
  "video_prompt": "按生效视频提示词模板为本段写的成文分镜提示词全文,含 @资产名 引用,结尾一行:严禁任何字幕,严禁背景音乐",
  ${shotsShape}
} ], "self_check": { "segment_count": 数字, "covered_lines": [0, 最后一行行号] } }`,
    `${shotsRule}video_prompt 必填非空;duration_sec 给 1-60 的整数;scene_ref 从场次清单选;行号用剧本行号(L 后的数字)。`,
    "- covered_line_range 相邻紧接、铺满全部剧本行;assets 只许引用资产库清单里的名字,一个字符都不许改。",
    "- 禁止把「默认视频风格 / 色调 / 运镜」等风格描述文字捏造成资产名——assets 只能来自资产库清单,风格信息写进 style 与 video_prompt。",
  ].join("\n");
}

