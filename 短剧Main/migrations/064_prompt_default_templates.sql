一、 核心提示词公式：5 段式结构
为了确保生成的视频具有“导演级”的可控性，每一条提示词应遵循以下结构：

 [@引用标签]+[主体角色] + [核心动作] + [镜头语言] + [环境光影与风格]
引用标签 (@References)：这是 Seedance 2.0 的核心。通过 @图N 锁定角色/场景图片，通过 @音频N 绑定角色声音（仅「有音色=是」的角色才有 @音频N 可用）。
主体角色 (Subject)：详细描述角色的年龄、着装、材质（如：一位穿着磨损皮革夹克的青年，面部有细微汗水）。
核心动作 (Action)：使用现在进行时，明确动作的幅度与频率。建议每 5-10 秒只描述一个主动作。
镜头语言 (Camera)：明确景别（Wide, Medium, Close-up）和运动轨迹（Dolly-in, Pan, Orbit）。建议标注镜头焦距（如 35mm, 85mm）。
环境与风格 (Environment & Style)：描述光影性质（软光、逆光、丁达尔效应）和画面风格（胶片质感、废土工业风、2K 高清），与上下文中的“全局风格”对应。


