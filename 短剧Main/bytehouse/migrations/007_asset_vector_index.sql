CREATE TABLE IF NOT EXISTS {{database}}.`asset_vector_index`
(
    `index_id` String COMMENT '由来源身份、模型、维度和索引版本生成的检索行稳定标识',
    `document_id` String COMMENT '关联 asset_vec_documents.document_id 的详情投影稳定标识',
    `source_table` LowCardinality(String) COMMENT 'PostgreSQL canonical 来源表，仅为 asset_entities 或 asset_variants',
    `source_id` String COMMENT 'PostgreSQL canonical 来源稳定 ID，不使用 ByteHouse 投影或媒体 ID',
    `detail_projection_table` LowCardinality(String) COMMENT 'ByteHouse 详情投影表，当前固定为 asset_vec_documents',
    `detail_projection_id` String COMMENT 'ByteHouse 详情投影稳定 ID，当前等于 document_id',
    `asset_entity_id` String COMMENT 'PostgreSQL asset_entities.id，变体行仍保留父实体 ID',
    `asset_variant_id` Nullable(String) COMMENT 'PostgreSQL asset_variants.id，实体行为空',
    `owner_subject_key` String COMMENT '来源资产 owner 的受控主体标识，不存姓名或联系方式',
    `source_project_id` Nullable(String) COMMENT '来源项目标识，不等同于当前项目可用范围',
    `authorized_project_ids` Array(String) COMMENT '有效 project_asset_refs 的安全预过滤投影，最终仍由应用 API 鉴权',
    `asset_kind` LowCardinality(String) COMMENT '开放资产类型词表值，新增创作类型不改 schema',
    `role` Nullable(String) COMMENT '资产职责开放词表值，不另造平行分类',
    `usage_mode` Nullable(String) COMMENT '资产使用方式开放词表值',
    `variant_kind` Nullable(String) COMMENT '变体类型开放词表值，实体行为空',
    `variant_name` Nullable(String) COMMENT '变体安全展示名，实体行为空',
    `variant_is_primary` Nullable(UInt8) COMMENT '变体是否主造型，实体行为空',
    `variant_sort_order` Nullable(UInt32) COMMENT '变体稳定排序，实体行为空',
    `visibility` LowCardinality(String) COMMENT '来源可见性预过滤值，不替代最终鉴权',
    `search_clearance` UInt8 COMMENT '来源 clearance.search 布尔投影，索引行固定为已放行',
    `source_status` LowCardinality(String) COMMENT '来源资产或变体审核四态原值，索引行固定为 approved',
    `parent_entity_status` Nullable(String) COMMENT '变体行父资产审核状态，实体行为空',
    `source_sensitivity_level` LowCardinality(String) COMMENT '全部来源中最高敏感等级，S3 来源禁止进入本表',
    `sensitivity_level` LowCardinality(String) COMMENT '本检索投影确认后的敏感等级，仅允许 S0、S1、S2',
    `sensitivity_inheritance` LowCardinality(String) COMMENT '敏感等级继承方式，降级必须带可审计理由与证据',
    `classification_state` LowCardinality(String) COMMENT '分类候选或确认状态，本检索投影仅允许 confirmed',
    `classification_source` LowCardinality(String) COMMENT '自动候选经人审、人工直接确认或人工纠正等分类来源',
    `classification_rule_id` String COMMENT '产生分类候选或人工确认依据的稳定规则编号',
    `classification_confidence` Nullable(Float32) COMMENT '自动分类候选置信度，人工直接确认时允许为空',
    `classification_reason` String COMMENT '人工纠正或敏感等级降级理由，无此动作时可为空字符串',
    `classification_evidence` String COMMENT '脱敏证据引用 JSON，不保存原始人脸、声纹、密钥或正文',
    `classification_confirmed_by` String COMMENT '最终分类确认人的 actor_ref，不存真名',
    `classification_confirmed_at` DateTime64(3, 'UTC') COMMENT '最终分类人工确认 UTC 时间',
    `policy_version` String COMMENT '数据分级与处理策略版本',
    `review_due_at` Nullable(DateTime64(3, 'UTC')) COMMENT '下次人工复核截止 UTC 时间，无复核周期时为空',
    `rights_state` LowCardinality(String) COMMENT '版权与肖像授权状态，独立于敏感等级',
    `rights_ref` String COMMENT '授权或权利证明的受控引用，不保存证明正文',
    `clearance_state` LowCardinality(String) COMMENT '检索与复用放行状态，独立于 rights 和 publication',
    `clearance_ref` String COMMENT '放行裁决或策略的受控引用',
    `review_state` LowCardinality(String) COMMENT '人工审核结果，仅允许 human_accepted 或 human_corrected',
    `publication_state` LowCardinality(String) COMMENT '发布状态，索引行固定为 approved',
    `publication_ref` String COMMENT '发布批准记录的受控引用',
    `transfer_rule` LowCardinality(String) COMMENT '跨项目或外部传输规则，独立于敏感等级',
    `transfer_ref` Nullable(String) COMMENT '传输规则或批准记录引用，不适用时为空',
    `retention_class` LowCardinality(String) COMMENT '保留期类别，独立于敏感等级和发布状态',
    `retention_ref` String COMMENT '保留策略或裁决的受控引用',
    `title` String COMMENT '由批准字段可复现编译的安全检索标题',
    `summary` String COMMENT '由批准字段可复现编译的安全摘要，不编造来源事实',
    `content` String COMMENT '用于全文倒排的安全正文，不含提示词、URL、凭据或供应商载荷',
    `text_for_embedding` String COMMENT '用于生成向量的规范化安全文本，不含媒体二进制或 URL',
    `embedding_model` LowCardinality(String) COMMENT '固定为 doubao-embedding-vision-251215 的检索模型',
    `embedding_dimension` UInt16 COMMENT '已授权 smoke 确认的固定向量维度 1024',
    `embedding` Array(Float32) COMMENT 'text_for_embedding 对应的一条向量，媒体不单独成索引行',
    `embedding_input_sha256` FixedString(64) COMMENT '规范化向量输入摘要，用于变更与重放审计',
    `index_version` UInt64 COMMENT '索引投影或重嵌版本，同一来源内单调演进',
    `source_updated_at` DateTime64(3, 'UTC') COMMENT 'PostgreSQL 来源对象最近变更 UTC 时间',
    `source_revision` UInt64 COMMENT '持久 canonical 来源修订序号，禁止使用进程内计数',
    `indexed_at` DateTime64(3, 'UTC') COMMENT '检索文档与向量计算完成 UTC 时间',
    `synced_at` DateTime64(3, 'UTC') COMMENT '本行写入 ByteHouse 的 UTC 时间',
    `retention_until` DateTime64(3, 'UTC') COMMENT '由来源生命周期与保留策略计算的删除时间',
    INDEX asset_vector_content_inverted content TYPE inverted(2) GRANULARITY 1,
    INDEX asset_vector_embedding_hnsw embedding TYPE HNSW('DIM=1024, METRIC=COSINE') GRANULARITY 1,
    CONSTRAINT `asset_vector_index_id_nonempty` CHECK length(index_id) > 0 AND length(document_id) > 0,
    CONSTRAINT `asset_vector_index_source_nonempty` CHECK length(source_table) > 0 AND length(source_id) > 0,
    CONSTRAINT `asset_vector_index_source_table_valid` CHECK source_table IN ('asset_entities', 'asset_variants'),
    CONSTRAINT `asset_vector_index_detail_valid` CHECK detail_projection_table = 'asset_vec_documents' AND detail_projection_id = document_id,
    CONSTRAINT `asset_vector_index_entity_nonempty` CHECK length(asset_entity_id) > 0 AND length(owner_subject_key) > 0,
    CONSTRAINT `asset_vector_index_search_allowed` CHECK search_clearance = 1 AND source_status = 'approved' AND (parent_entity_status IS NULL OR parent_entity_status = 'approved'),
    CONSTRAINT `asset_vector_index_subject_shape_valid` CHECK (source_table = 'asset_entities' AND source_id = asset_entity_id AND asset_variant_id IS NULL AND parent_entity_status IS NULL) OR (source_table = 'asset_variants' AND asset_variant_id IS NOT NULL AND source_id = coalesce(asset_variant_id, '') AND parent_entity_status = 'approved'),
    CONSTRAINT `asset_vector_index_sensitivity_valid` CHECK source_sensitivity_level IN ('S0', 'S1', 'S2') AND sensitivity_level IN ('S0', 'S1', 'S2'),
    CONSTRAINT `asset_vector_index_sensitivity_inheritance_valid` CHECK sensitivity_inheritance IN ('source_equal', 'source_max', 'audited_downgrade'),
    CONSTRAINT `asset_vector_index_sensitivity_not_lowered` CHECK sensitivity_inheritance = 'audited_downgrade' OR (source_sensitivity_level = 'S0' AND sensitivity_level IN ('S0', 'S1', 'S2')) OR (source_sensitivity_level = 'S1' AND sensitivity_level IN ('S1', 'S2')) OR (source_sensitivity_level = 'S2' AND sensitivity_level = 'S2'),
    CONSTRAINT `asset_vector_index_downgrade_audited` CHECK sensitivity_inheritance != 'audited_downgrade' OR (length(classification_reason) > 0 AND length(classification_evidence) > 0),
    CONSTRAINT `asset_vector_index_classification_confirmed` CHECK classification_state = 'confirmed' AND length(classification_source) > 0 AND length(classification_rule_id) > 0 AND length(classification_confirmed_by) > 0 AND length(policy_version) > 0,
    CONSTRAINT `asset_vector_index_confidence_valid` CHECK classification_confidence IS NULL OR (classification_confidence >= 0 AND classification_confidence <= 1),
    CONSTRAINT `asset_vector_index_human_reviewed` CHECK review_state IN ('human_accepted', 'human_corrected') AND (review_state != 'human_corrected' OR (length(classification_reason) > 0 AND length(classification_evidence) > 0)),
    CONSTRAINT `asset_vector_index_governance_released` CHECK rights_state = 'cleared' AND length(rights_ref) > 0 AND clearance_state = 'cleared' AND length(clearance_ref) > 0 AND publication_state = 'approved' AND length(publication_ref) > 0,
    CONSTRAINT `asset_vector_index_transfer_valid` CHECK length(transfer_rule) > 0 AND (transfer_rule = 'not_applicable' OR length(coalesce(transfer_ref, '')) > 0),
    CONSTRAINT `asset_vector_index_retention_valid` CHECK length(retention_class) > 0 AND length(retention_ref) > 0,
    CONSTRAINT `asset_vector_index_content_nonempty` CHECK length(title) > 0 AND length(content) > 0 AND length(text_for_embedding) > 0,
    CONSTRAINT `asset_vector_index_model_fixed` CHECK embedding_model = 'doubao-embedding-vision-251215',
    CONSTRAINT `asset_vector_index_dimension_fixed` CHECK embedding_dimension = 1024 AND length(embedding) = 1024,
    CONSTRAINT `asset_vector_index_source_revision_valid` CHECK source_revision > 0 AND index_version > 0
)
ENGINE = CnchMergeTree()
ORDER BY (visibility, sensitivity_level, asset_kind, embedding_model, embedding_dimension, source_table, source_id, source_revision, index_version, index_id)
PARTITION BY toYYYYMM(indexed_at)
PRIMARY KEY (visibility, sensitivity_level, asset_kind, embedding_model, embedding_dimension, source_table, source_id, source_revision, index_version, index_id)
TTL toDateTime(retention_until) DELETE
SETTINGS index_granularity = 128, index_granularity_bytes = 0
COMMENT = '经人审与治理放行的资产全文和向量检索投影；S3 禁入，命中仍回 PostgreSQL 鉴权';

CREATE VIEW IF NOT EXISTS {{database}}.`v_asset_vector_index_latest` AS
SELECT *
FROM {{database}}.`asset_vector_index`
ORDER BY source_revision DESC, index_version DESC, synced_at DESC
LIMIT 1 BY source_table, source_id;
